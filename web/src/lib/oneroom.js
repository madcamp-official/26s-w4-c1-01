// 침대 규격 라벨 — 한국은 '폭'으로 부른다(길이는 대부분 200 고정).
// 목록에서 킹·퀸만 잔뜩 보이는 걸 막고, 내 방에 뭐가 들어가는지 바로 읽히게.
export function bedSizeLabel(item) {
  if (item?.cat !== '침대') return null;
  const w = item.w;
  if (!w) return null;
  if (w <= 105) return '싱글';
  if (w <= 125) return '슈퍼싱글';
  if (w <= 147) return '더블';
  if (w <= 157) return '퀸';
  if (w <= 175) return '킹';
  return '라지킹';
}
